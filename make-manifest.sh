#!/bin/sh
set -eu
cd "$(dirname "$0")"
FILES="index.html jb.html style.css launch.js service-worker.js meme.png vtm-gaming-bg.png
jb.js core.js mem.js int64.js ps4_offsets.js afterglow.js
patchset-1400.bin patchset-1352.bin hen.bin goldhen.bin"
{
  echo "CACHE MANIFEST"
  echo "# VTM14 ViralTech Market offline cache v3"
  echo "# Generated by make-manifest.sh"
  echo
  for f in $FILES; do
    [ -f "$f" ] || { echo "missing: $f" >&2; exit 1; }
    printf '%s #%s\n' "$f" "$(sha256sum "$f" | cut -c1-32)"
  done
  echo
  echo "NETWORK:"
  echo "*"
} > cache.appapp
mv cache.appapp cache.appcache
echo "Manifest regenerated."
